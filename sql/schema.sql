-- Импортировать в пустую учебную базу MySQL 8.0.16+.
SET NAMES utf8mb4;
SET time_zone = '+00:00';

CREATE TABLE USER_TABLE (
    USER_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    LOGIN VARCHAR(64) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Четыре таблицы из уроков 2–4; исходные имена полей сохранены.
CREATE TABLE DEVICE_TABLE (
    DEVICE_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    LOGIN CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    PASSWORD CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    LAST_SEEN DATETIME NULL,
    WINDOW_START DATETIME NULL,
    REQUEST_COUNT INT UNSIGNED NOT NULL DEFAULT 0,
    BLOCKED_UNTIL DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE TEMPERATURE_TABLE (
    DEVICE_ID INT UNSIGNED PRIMARY KEY,
    TEMPERATURE SMALLINT NULL,
    DATE_TIME DATETIME NOT NULL,
    FOREIGN KEY (DEVICE_ID) REFERENCES DEVICE_TABLE(DEVICE_ID),
    CHECK (TEMPERATURE IS NULL OR TEMPERATURE BETWEEN -550 AND 1250)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE OUT_STATE_TABLE (
    DEVICE_ID INT UNSIGNED PRIMARY KEY,
    OUT_STATE TINYINT NOT NULL,
    DATE_TIME DATETIME NOT NULL,
    FOREIGN KEY (DEVICE_ID) REFERENCES DEVICE_TABLE(DEVICE_ID),
    CHECK (OUT_STATE IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE COMMAND_TABLE (
    DEVICE_ID INT UNSIGNED PRIMARY KEY,
    COMMAND TINYINT NOT NULL,
    DATE_TIME DATETIME NOT NULL,
    FOREIGN KEY (DEVICE_ID) REFERENCES DEVICE_TABLE(DEVICE_ID),
    CHECK (COMMAND IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE USER_DEVICE_TABLE (
    USER_ID INT UNSIGNED NOT NULL,
    DEVICE_ID INT UNSIGNED NOT NULL,
    ROLE VARCHAR(12) NOT NULL DEFAULT 'operator',
    WINDOW_START DATETIME NULL,
    REQUEST_COUNT INT UNSIGNED NOT NULL DEFAULT 0,
    BLOCKED_UNTIL DATETIME NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID),
    FOREIGN KEY (USER_ID) REFERENCES USER_TABLE(USER_ID),
    FOREIGN KEY (DEVICE_ID) REFERENCES DEVICE_TABLE(DEVICE_ID),
    CHECK (ROLE IN ('viewer','operator'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE USER_ACTION_TABLE (
    ACTION_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    USER_ID INT UNSIGNED NOT NULL,
    DEVICE_ID INT UNSIGNED NOT NULL,
    ACTION VARCHAR(12) NOT NULL,
    COMMAND TINYINT NULL,
    DATE_TIME DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RESULT VARCHAR(20) NOT NULL DEFAULT 'allowed',
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES USER_DEVICE_TABLE(USER_ID, DEVICE_ID),
    CHECK (ACTION IN ('view','control','history','simulate')),
    CHECK (COMMAND IS NULL OR COMMAND IN (0,1)),
    CHECK ((ACTION='control' AND COMMAND IS NOT NULL) OR (ACTION<>'control' AND COMMAND IS NULL)),
    CHECK (RESULT IN ('allowed','forbidden','user_blocked','device_blocked')),
    INDEX (DEVICE_ID, ACTION_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DEVICE_REQUEST_TABLE (
    REQUEST_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    DEVICE_ID INT UNSIGNED NOT NULL,
    DATE_TIME DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RESULT VARCHAR(12) NOT NULL DEFAULT 'allowed',
    FOREIGN KEY (DEVICE_ID) REFERENCES DEVICE_TABLE(DEVICE_ID),
    CHECK (RESULT IN ('allowed','blocked')),
    INDEX (DEVICE_ID, REQUEST_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
